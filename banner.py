def print_banner():
    if 'NO_COLOR' in os.environ or os.environ.get('TERM') == 'dumb':
        print_plain_banner()
    elif os.environ.get('COLORTERM') in ('truecolor', '24bit'):
        print_truecolor_banner()
    elif '256color' in os.environ.get('TERM', ''):
        print_256_banner()
    else:
        print_16_banner()

